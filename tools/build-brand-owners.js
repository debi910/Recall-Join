// Builds core/brand-owners.js: for every brand on the bundled CDSCO lists, the companies
// that sell it at retail. Shops' billing software names the brand owner ("Glaxo SmithKline"
// for Augmentin) while CDSCO names the plant that made it ("Medreich Ltd."), so without
// this table a real recall reaches the pharmacist as "maker differs".
// Source: A-Z Medicine Dataset of India (Kaggle, shudhanshusingh; 253,973 retail listings).
// Each owner keeps the listing ids it came from, so the eval can leave a listing out.
// Usage: node tools/build-brand-owners.js <A_Z_medicines_dataset_of_India.csv> > core/brand-owners.js
import { readFileSync, readdirSync } from 'node:fs';
import { parseCsv } from '../core/csv.js';
import { brandKey, brandMatcher } from '../core/brands.js';

const [head, ...rows] = parseCsv(readFileSync(process.argv[2], 'utf8'));
const [iName, iMfr, iC1, iC2] = ['name', 'manufacturer_name', 'short_composition1', 'short_composition2'].map((c) => head.indexOf(c));
const catalogue = rows.map((r) => ({ id: Number(r[0]), name: r[iName], mfr: r[iMfr].trim(), comp: `${r[iC1]} ${r[iC2]}` }));
const byLetter = Map.groupBy(catalogue, (c) => c.name.trim()[0]?.toUpperCase());

const dir = new URL('../data/nsq/', import.meta.url);
const nsq = readdirSync(dir).sort().flatMap((f) => JSON.parse(readFileSync(new URL(f, dir), 'utf8')));

const table = {};
for (const r of nsq) {
  const key = brandKey(r.product), test = brandMatcher(r.product);
  if (!test || table[key]) continue;
  const owners = {};
  for (const c of (byLetter.get(key[0]) ?? []).filter(test)) (owners[c.mfr] ??= []).push(c.id);
  if (Object.keys(owners).length) table[key] = owners;
}
process.stdout.write(`// Generated by tools/build-brand-owners.js. Do not edit by hand.
// Brand (as CDSCO writes it) -> retail company -> catalogue listing ids.
export const BRAND_OWNERS = ${JSON.stringify(table, null, 0).replace(/\],"/g, '],\n"').replace(/\},"/g, '},\n"')};
`);
